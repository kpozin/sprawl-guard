const RELEASE_COMMIT = "0123456789abcdef0123456789abcdef01234567";
const temporaryDirectories: string[] = [];

afterEach(() => {
  for (const directory of temporaryDirectories.splice(0)) {
    fs.rmSync(directory, { force: true, recursive: true });
  }
});

function releaseExpectation(commit = RELEASE_COMMIT) {
  const parsed = parseReleaseSourceExpectation(
    [commit, `v${PACKAGE_VERSION}`],
    PACKAGE_VERSION,
  );
  assert.equal(parsed.kind, "ok");
  if (parsed.kind !== "ok") {
    throw new Error("test release expectation must parse");
  }
  return parsed.expectation;
}

function createCargoCandidateWorkspace(): string {
  const workspaceRoot = fs.mkdtempSync(
    path.join(os.tmpdir(), "sprawl-guard-cargo-candidate-"),
  );
  temporaryDirectories.push(workspaceRoot);
  fs.mkdirSync(path.join(workspaceRoot, "crates/sprawl-guard-lib/src"), {
    recursive: true,
  });
  fs.mkdirSync(path.join(workspaceRoot, "crates/sprawl-guard/src"), {
    recursive: true,
  });
  fs.mkdirSync(path.join(workspaceRoot, ".cargo"));
  fs.writeFileSync(
    path.join(workspaceRoot, ".cargo/config.toml"),
    "[net]\noffline = true\n",
  );
  fs.writeFileSync(
    path.join(workspaceRoot, "Cargo.toml"),
    '[workspace]\nmembers = ["crates/sprawl-guard-lib", "crates/sprawl-guard"]\nresolver = "2"\n',
  );
  fs.writeFileSync(
    path.join(workspaceRoot, "Cargo.lock"),
    `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "sprawl-guard"\nversion = "${PACKAGE_VERSION}"\ndependencies = [\n "sprawl-guard-lib",\n]\n\n[[package]]\nname = "sprawl-guard-lib"\nversion = "${PACKAGE_VERSION}"\n`,
  );
  fs.writeFileSync(
    path.join(workspaceRoot, "crates/sprawl-guard-lib/Cargo.toml"),
    `[package]\nname = "sprawl-guard-lib"\nversion = "${PACKAGE_VERSION}"\nedition = "2024"\ndescription = "test fixture"\nlicense = "MIT"\nrepository = "https://example.invalid/sprawl-guard"\n`,
  );
  fs.writeFileSync(
    path.join(workspaceRoot, "crates/sprawl-guard-lib/src/lib.rs"),
    "pub fn marker() {}\n",
  );
  fs.writeFileSync(
    path.join(workspaceRoot, "crates/sprawl-guard/Cargo.toml"),
    `[package]\nname = "sprawl-guard"\nversion = "${PACKAGE_VERSION}"\nedition = "2024"\ndescription = "test fixture"\nlicense = "MIT"\nrepository = "https://example.invalid/sprawl-guard"\n\n[dependencies]\nsprawl-guard-lib = { path = "../sprawl-guard-lib", version = "=${PACKAGE_VERSION}" }\n`,
  );
  fs.writeFileSync(
    path.join(workspaceRoot, "crates/sprawl-guard/src/main.rs"),
    "fn main() { sprawl_guard_lib::marker(); }\n",
  );
  return workspaceRoot;
}

function prepareCandidateWorkspace(): string {
  const workspaceRoot = createCargoCandidateWorkspace();
  assert.deepEqual(
    prepareCargoCrates({ expectation: releaseExpectation(), workspaceRoot }),
    { kind: "ok" },
  );
  return workspaceRoot;
}

function libraryPublicationRequest(
  workspaceRoot: string,
): CargoPublicationRequest {
  const request = cargoPublicationRequests({ workspaceRoot })[0];
  if (request === undefined) {
    throw new Error("test workspace must have a library publication request");
  }
  return request;
}

function cliPublicationRequest(workspaceRoot: string): CargoPublicationRequest {
  const request = cargoPublicationRequests({ workspaceRoot })[1];
  if (request === undefined) {
    throw new Error("test workspace must have a CLI publication request");
  }
  return request;
}

function candidateManifestPath(workspaceRoot: string): string {
  return path.join(
    workspaceRoot,
    "target/package/sprawl-guard-publication.json",
  );
}

function runFixtureGit(workspaceRoot: string, args: readonly string[]): string {
  const result = spawnSync("git", args, {
    cwd: workspaceRoot,
    encoding: "utf8",
  });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
}

describe("Cargo release commands", () => {
  describe("when uploading after preparation", () => {
    it("pins crates.io and skips dependency-executing verification", () => {
      assert.deepEqual(cargoPublishArguments("sprawl-guard"), [
        "publish",
        "--locked",
        "--no-verify",
        "--registry",
        "crates-io",
        "--package",
        "sprawl-guard",
      ]);
    });
  });
});

describe("Cargo publication candidate", () => {
  describe("when both archives are prepared from the frozen source", () => {
    it("records both candidates and validates them without registry credentials", () => {
      const workspaceRoot = prepareCandidateWorkspace();

      const validated = validateCargoPublicationCandidate({
        expectation: releaseExpectation(),
        workspaceRoot,
      });
      const repeated = prepareCargoCrates({
        expectation: releaseExpectation(),
        workspaceRoot,
      });

      assert.equal(validated.kind, "ok");
      assert.deepEqual(repeated, { kind: "ok" });
      assert.deepEqual(
        validated.kind === "ok"
          ? [...validated.checksums.keys()]
          : [],
        ["sprawl-guard-lib", "sprawl-guard"],
      );
    });
  });

  describe("when the prepared archive changes", () => {
    it("rejects the candidate before publication", async () => {
      const workspaceRoot = prepareCandidateWorkspace();
      const libraryRequest = libraryPublicationRequest(workspaceRoot);
      fs.appendFileSync(libraryRequest.archivePath, "tampered");

      const validated = validateCargoPublicationCandidate({
        expectation: releaseExpectation(),
        workspaceRoot,
      });
      const publication = await publishCargoCrates({
        expectation: releaseExpectation(),
        workspaceRoot,
      });

      assert.equal(validated.kind, "failed");
      assert.match(validated.detail, /differs from its frozen candidate/u);
      assert.deepEqual(publication, validated);
    });
  });

  describe("when the prepared CLI archive changes", () => {
    it("rejects the candidate before publishing either crate", async () => {
      const workspaceRoot = prepareCandidateWorkspace();
      const cliRequest = cliPublicationRequest(workspaceRoot);
      fs.appendFileSync(cliRequest.archivePath, "tampered");

      const validated = validateCargoPublicationCandidate({
        expectation: releaseExpectation(),
        workspaceRoot,
      });
      const publication = await publishCargoCrates({
        expectation: releaseExpectation(),
        workspaceRoot,
      });

      assert.equal(validated.kind, "failed");
      assert.equal(validated.packageName, "sprawl-guard");
      assert.match(validated.detail, /differs from its frozen candidate/u);
      assert.deepEqual(publication, validated);
    });
  });

  describe("when the candidate names a different release source", () => {
    it("rejects the source binding", () => {
      const workspaceRoot = prepareCandidateWorkspace();

      const validated = validateCargoPublicationCandidate({
        expectation: releaseExpectation(
          "89abcdef0123456789abcdef0123456789abcdef",
        ),
        workspaceRoot,
      });

      assert.equal(validated.kind, "failed");
      assert.match(
        validated.detail,
        /does not match the frozen release source/u,
      );
    });
  });

  describe("when the candidate manifest contains an unknown field", () => {
    it("rejects the manifest schema", () => {
      const workspaceRoot = prepareCandidateWorkspace();
      const manifestPath = candidateManifestPath(workspaceRoot);
      const manifest = JSON.parse(
        fs.readFileSync(manifestPath, "utf8"),
      ) as Record<string, unknown>;
      fs.writeFileSync(
        manifestPath,
        `${JSON.stringify({ ...manifest, unexpected: true })}\n`,
      );

      const validated = validateCargoPublicationCandidate({
        expectation: releaseExpectation(),
        workspaceRoot,
      });

      assert.equal(validated.kind, "failed");
      assert.match(validated.detail, /invalid Cargo publication candidate/u);
    });
  });

  describe("when the candidate package order differs from the protocol", () => {
    it("rejects the manifest before reading the wrong archive", () => {
      const workspaceRoot = prepareCandidateWorkspace();
      const manifestPath = candidateManifestPath(workspaceRoot);
      const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8")) as {
        packages: Array<{ packageName: string }>;
      };
      if (manifest.packages[0] === undefined) {
        assert.fail("candidate fixture must contain the library package");
      }
      manifest.packages[0].packageName = "sprawl-guard";
      fs.writeFileSync(manifestPath, `${JSON.stringify(manifest)}\n`);

      const validated = validateCargoPublicationCandidate({
        expectation: releaseExpectation(),
        workspaceRoot,
      });

      assert.equal(validated.kind, "failed");
      assert.match(validated.detail, /package order is invalid/u);
    });
  });

  describe("when the archive has another hard link", () => {
    it("rejects a candidate whose bytes can change through another path", () => {
      const workspaceRoot = prepareCandidateWorkspace();
      const libraryRequest = libraryPublicationRequest(workspaceRoot);
      fs.linkSync(
        libraryRequest.archivePath,
        path.join(workspaceRoot, "linked-library.crate"),
      );

      const validated = validateCargoPublicationCandidate({
        expectation: releaseExpectation(),
        workspaceRoot,
      });

      assert.equal(validated.kind, "failed");
      assert.match(validated.detail, /not an independent regular file/u);
    });
  });
});

describe("createFrozenReleaseCheckout", () => {
  describe("when the reviewed commit and tag identify the source", () => {
    it("publishes from an isolated detached checkout", () => {
      const workspaceRoot = fs.mkdtempSync(
        path.join(os.tmpdir(), "sprawl-guard-cargo-source-"),
      );
      temporaryDirectories.push(workspaceRoot);
      runFixtureGit(workspaceRoot, ["init", "--quiet"]);
      fs.writeFileSync(path.join(workspaceRoot, "source.txt"), "reviewed\n");
      runFixtureGit(workspaceRoot, ["add", "source.txt"]);
      runFixtureGit(workspaceRoot, [
        "-c",
        "user.name=Test",
        "-c",
        "user.email=test@example.invalid",
        "commit",
        "--quiet",
        "--message",
        "fixture",
      ]);
      const commit = runFixtureGit(workspaceRoot, ["rev-parse", "HEAD"]);
      runFixtureGit(workspaceRoot, ["tag", `v${PACKAGE_VERSION}`]);

      const frozen = createFrozenReleaseCheckout({
        expectation: releaseExpectation(commit),
        workspaceRoot,
      });
      if (frozen.kind !== "ok") {
        assert.fail(frozen.detail);
      }
      temporaryDirectories.push(frozen.temporaryRoot);
      fs.writeFileSync(path.join(workspaceRoot, "source.txt"), "changed\n");

      assert.notEqual(frozen.workspaceRoot, workspaceRoot);
      assert.equal(
        fs.readFileSync(path.join(frozen.workspaceRoot, "source.txt"), "utf8"),
        "reviewed\n",
      );
      assert.equal(
        runFixtureGit(frozen.workspaceRoot, ["rev-parse", "HEAD"]),
        commit,
      );
    });
  });
});

describe("inspectRemoteCargoArchive", () => {
  describe("when crates.io declares an oversized archive", () => {
    it("uses a request deadline and refuses to buffer the response", async () => {
      let requestHadSignal = false;
      const fetchMock = mock.method(
        globalThis,
        "fetch",
        async (_input: string | URL | Request, init?: RequestInit) => {
          requestHadSignal = init?.signal instanceof AbortSignal;
          return new Response(new Uint8Array(), {
            headers: { "content-length": "16777217" },
            status: 200,
          });
        },
      );
      let result;
      try {
        result = await inspectRemoteCargoArchive("sprawl-guard-lib");
      } finally {
        fetchMock.mock.restore();
      }

      assert.equal(requestHadSignal, true);
      assert.equal(result.kind, "permanent_failure");
      assert.match(result.detail, /exceeds 16777216 bytes/u);
    });
  });
});

