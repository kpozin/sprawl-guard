const LIBRARY_REQUEST: CargoPublicationRequest = {
  archivePath: `/release/sprawl-guard-lib-${PACKAGE_VERSION}.crate`,
  packageName: "sprawl-guard-lib",
  readiness: { kind: "archive_and_index" },
};
const CLI_REQUEST: CargoPublicationRequest = {
  archivePath: `/release/sprawl-guard-${PACKAGE_VERSION}.crate`,
  packageName: "sprawl-guard",
  readiness: { kind: "archive" },
};

function publicationOperations(args: {
  readonly archiveInspections: RemoteCargoArchiveInspection[];
  readonly events: string[];
  readonly indexInspections?: readonly ("ready" | "retry")[];
}): CargoPublicationOperations {
  const indexInspections = [...(args.indexInspections ?? ["ready"])];
  return {
    inspectCargoIndex: () => {
      args.events.push("inspect-index");
      const inspection = indexInspections.shift() ?? "retry";
      return inspection === "ready"
        ? { kind: "ready" }
        : { kind: "transient_failure", detail: "index not updated" };
    },
    inspectRemoteArchive: async () => {
      args.events.push("inspect-archive");
      return (
        args.archiveInspections.shift() ?? {
          kind: "permanent_failure",
          detail: "inspection queue exhausted",
        }
      );
    },
    packageCrate: () => {
      args.events.push("package");
      return { kind: "ok", checksum: "local" };
    },
    publishCrate: () => {
      args.events.push("publish");
      return { kind: "ok" };
    },
    sleepBeforeRetry: async () => {
      args.events.push("sleep");
    },
  };
}

describe("publishCargoPublicationRequests", () => {
  describe("when the later CLI version conflicts with the registry", () => {
    it("publishes neither crate", async () => {
      const events: string[] = [];
      const result = await publishCargoPublicationRequests({
        operations: {
          inspectCargoIndex: () => ({ kind: "ready" }),
          inspectRemoteArchive: async (packageName) => {
            events.push(`inspect:${packageName}`);
            return packageName === "sprawl-guard-lib"
              ? { kind: "ok", checksum: { kind: "absent" } }
              : {
                  kind: "ok",
                  checksum: { kind: "present", checksum: "remote-cli" },
                };
          },
          packageCrate: (request) => {
            events.push(`package:${request.packageName}`);
            return { kind: "ok", checksum: `local-${request.packageName}` };
          },
          publishCrate: (request) => {
            events.push(`publish:${request.packageName}`);
            return { kind: "ok" };
          },
          sleepBeforeRetry: async () => {},
        },
        requests: [LIBRARY_REQUEST, CLI_REQUEST],
      });

      assert.equal(result.kind, "failed");
      assert.deepEqual(events, [
        "package:sprawl-guard-lib",
        "inspect:sprawl-guard-lib",
        "inspect:sprawl-guard",
      ]);
    });
  });

  describe("when both crate versions are initially absent", () => {
    it("packages the CLI only after the library reaches the Cargo index", async () => {
      const events: string[] = [];
      const inspections = new Map<string, RemoteCargoArchiveInspection[]>([
        [
          "sprawl-guard-lib",
          [
            { kind: "ok", checksum: { kind: "absent" } },
            { kind: "ok", checksum: { kind: "absent" } },
            {
              kind: "ok",
              checksum: { kind: "present", checksum: "local-sprawl-guard-lib" },
            },
          ],
        ],
        [
          "sprawl-guard",
          [
            { kind: "ok", checksum: { kind: "absent" } },
            { kind: "ok", checksum: { kind: "absent" } },
            {
              kind: "ok",
              checksum: { kind: "present", checksum: "local-sprawl-guard" },
            },
          ],
        ],
      ]);
      const result = await publishCargoPublicationRequests({
        operations: {
          inspectCargoIndex: () => {
            events.push("inspect-index:sprawl-guard-lib");
            return { kind: "ready" };
          },
          inspectRemoteArchive: async (packageName) => {
            events.push(`inspect:${packageName}`);
            return (
              inspections.get(packageName)?.shift() ?? {
                kind: "permanent_failure",
                detail: `inspection queue exhausted for ${packageName}`,
              }
            );
          },
          packageCrate: (request) => {
            events.push(`package:${request.packageName}`);
            return { kind: "ok", checksum: `local-${request.packageName}` };
          },
          publishCrate: (request) => {
            events.push(`publish:${request.packageName}`);
            return { kind: "ok" };
          },
          sleepBeforeRetry: async () => {},
        },
        requests: [LIBRARY_REQUEST, CLI_REQUEST],
      });

      assert.deepEqual(result, { kind: "ok" });
      assert.deepEqual(events, [
        "package:sprawl-guard-lib",
        "inspect:sprawl-guard-lib",
        "inspect:sprawl-guard",
        "inspect:sprawl-guard-lib",
        "publish:sprawl-guard-lib",
        "inspect:sprawl-guard-lib",
        "inspect-index:sprawl-guard-lib",
        "package:sprawl-guard",
        "inspect:sprawl-guard",
        "publish:sprawl-guard",
        "inspect:sprawl-guard",
      ]);
    });
  });

  describe("when transient failures delay archive and index visibility", () => {
    it("retries both checks without repeating the upload", async () => {
      const events: string[] = [];

      const result = await publishCargoPublicationRequests({
        operations: publicationOperations({
          archiveInspections: [
            { kind: "transient_failure", detail: "HTTP 429" },
            { kind: "ok", checksum: { kind: "absent" } },
            { kind: "ok", checksum: { kind: "absent" } },
            { kind: "transient_failure", detail: "HTTP 503" },
            { kind: "ok", checksum: { kind: "present", checksum: "local" } },
          ],
          events,
          indexInspections: ["retry", "ready"],
        }),
        requests: [LIBRARY_REQUEST],
      });

      assert.deepEqual(result, { kind: "ok" });
      assert.deepEqual(events, [
        "package",
        "inspect-archive",
        "sleep",
        "inspect-archive",
        "inspect-archive",
        "publish",
        "inspect-archive",
        "sleep",
        "inspect-archive",
        "inspect-index",
        "sleep",
        "inspect-index",
      ]);
    });
  });

  describe("when the library archive already matches", () => {
    it("still waits until Cargo can resolve it from the index", async () => {
      const events: string[] = [];

      const result = await publishCargoPublicationRequests({
        operations: publicationOperations({
          archiveInspections: [
            { kind: "ok", checksum: { kind: "present", checksum: "local" } },
          ],
          events,
        }),
        requests: [LIBRARY_REQUEST],
      });

      assert.deepEqual(result, { kind: "ok" });
      assert.deepEqual(events, ["package", "inspect-archive", "inspect-index"]);
    });
  });
});

describe("reconcileCargoArchiveChecksum", () => {
  describe("when the crate version is absent", () => {
    it("requests publication", () => {
      assert.deepEqual(
        reconcileCargoArchiveChecksum({
          localChecksum: "local",
          remoteChecksum: { kind: "absent" },
        }),
        { kind: "publish" },
      );
    });
  });

  describe("when the published archive matches the packaged archive", () => {
    it("allows a resumed release to skip the crate", () => {
      assert.deepEqual(
        reconcileCargoArchiveChecksum({
          localChecksum: "same",
          remoteChecksum: { kind: "present", checksum: "same" },
        }),
        { kind: "skip" },
      );
    });
  });

  describe("when the published archive differs from the packaged archive", () => {
    it("stops rather than replacing the immutable crate version", () => {
      assert.deepEqual(
        reconcileCargoArchiveChecksum({
          localChecksum: "local",
          remoteChecksum: { kind: "present", checksum: "remote" },
        }),
        {
          kind: "checksum_mismatch",
          localChecksum: "local",
          remoteChecksum: "remote",
        },
      );
    });
  });
});
